<?php

namespace Tests\Feature;

use App\Models\AuditLog;
use App\Models\EggGradingDaily;
use App\Models\EggProduction;
use App\Models\EggSale;
use App\Models\Expense;
use App\Models\User;
use App\Support\FarmReport;
use Illuminate\Foundation\Testing\RefreshDatabase;
use PhpOffice\PhpSpreadsheet\IOFactory;
use Tests\TestCase;

class CompleteReportTest extends TestCase
{
    use RefreshDatabase;

    private User $admin;
    private array $range = ['start_date' => '2026-10-10', 'end_date' => '2026-10-13'];

    protected function setUp(): void
    {
        parent::setUp();
        $this->travelTo('2026-10-13 02:00:00'); // 10:00 Manila
        $this->admin = User::factory()->create(['role' => 'admin', 'name' => 'Ada Admin']);

        EggProduction::create(['date' => '2026-10-11', 'eggs_collected' => 4000, 'active_hens' => 5000, 'mortality' => 2]);
        EggProduction::create(['date' => '2026-10-12', 'eggs_collected' => 4200, 'active_hens' => 5000, 'mortality' => 1]);
        EggSale::create(['date' => '2026-10-12', 'egg_size' => 'Medium', 'quantity' => 1000, 'price_per_unit' => 7, 'total_amount' => 7000]);
        EggSale::create(['date' => '2026-10-12', 'egg_size' => 'Large', 'quantity' => 777, 'price_per_unit' => 8, 'total_amount' => 6216, 'approval_status' => 'pending']);
        EggGradingDaily::create(['date' => '2026-10-12', 'category' => 'Medium', 'cases' => 2, 'trays' => 9, 'pieces' => 10]);
        Expense::create(['date' => '2026-10-12', 'category' => 'feed', 'description' => 'Layer mash', 'amount' => 3000, 'quantity' => 2, 'unit' => 'bag', 'unit_price' => 1500, 'kg_total' => 100]);
    }

    private function csv(array $params): string
    {
        return $this->actingAs($this->admin)->get(route('reports.export.csv', $this->range + $params))->assertOk()->streamedContent();
    }

    /** The CSV parsed into rows (fields are quoted when they contain spaces). */
    private function rows(string $body): array
    {
        return array_map('str_getcsv', array_filter(explode("\n", $body), fn ($l) => $l !== ''));
    }

    private function assertHasRow(array $expected, string $body): void
    {
        $this->assertContains($expected, $this->rows($body), 'Row not found: ' . implode(',', $expected));
    }

    public function test_csv_contains_ticked_sections_and_omits_the_rest(): void
    {
        $body = $this->csv(['sections' => ['summary', 'sales', 'expenses']]);

        $this->assertStringContainsString('== Summary ==', $body);
        $this->assertStringContainsString('== Sales & Revenue ==', $body);
        $this->assertStringContainsString('== Feed & Electricity Expenses ==', $body);
        $this->assertStringNotContainsString('== Batch Traceability ==', $body);
        $this->assertStringNotContainsString('== Daily Breakdown ==', $body);
        $this->assertStringContainsString('== Basis & definitions ==', $body);
        $this->assertHasRow(['Sections included', 'Summary, Sales & Revenue, Feed & Electricity Expenses'], $body);
    }

    public function test_no_sections_parameter_means_everything(): void
    {
        $body = $this->csv([]);
        foreach (FarmReport::SECTIONS as $title) {
            $this->assertStringContainsString("== {$title} ==", $body);
        }
    }

    public function test_totals_match_the_page_and_pending_is_excluded(): void
    {
        $page = $this->actingAs($this->admin)->get(route('reports.index', $this->range))->assertOk();
        $page->assertSee('8,200')->assertSee('1,000'); // produced, sold (approved only)

        $body = $this->csv(['sections' => ['summary', 'daily']]);
        $this->assertHasRow(['Total eggs produced', '8200'], $body);
        $this->assertHasRow(['Total eggs sold', '1000'], $body);       // not 1,777: the pending sale is left out
        $this->assertHasRow(['Total revenue (PHP)', '7000.00'], $body);
        $this->assertHasRow(['TOTAL', '8200', '1000', '3', '7000.00', '3000.00', '82', '7200'], $body);
        $this->assertStringNotContainsString('6216', $body);
    }

    public function test_header_has_generated_by_and_manila_time(): void
    {
        $body = $this->csv(['sections' => ['summary']]);
        $this->assertHasRow(['SPC Farm Magalang — Farm Production & Sales Report'], $body);
        $this->assertHasRow(['Generated by', 'Ada Admin (admin)'], $body);
        $this->assertHasRow(['Generated at (Asia/Manila)', '2026-10-13 10:00'], $body);
        $this->assertHasRow(['Only approved records are included.'], $body);
    }

    public function test_pdf_renders_with_charts_and_excel_has_one_sheet_per_section(): void
    {
        $pdf = $this->actingAs($this->admin)->get(route('reports.export.pdf', $this->range))->assertOk();
        $this->assertSame('application/pdf', $pdf->headers->get('content-type'));
        $this->assertStringStartsWith('%PDF', $pdf->getContent());

        $xlsx = $this->actingAs($this->admin)->get(route('reports.export.excel', $this->range + ['sections' => ['summary', 'charts', 'grading']]))->assertOk();
        $path = tempnam(sys_get_temp_dir(), 'rep') . '.xlsx';
        file_put_contents($path, $xlsx->getFile()->getContent());
        $names = IOFactory::load($path)->getSheetNames();
        unlink($path);
        $this->assertSame(['Report', 'Summary', 'Production & Revenue charts', 'Egg Size (grading) Breakdown', 'Basis & definitions'], $names);
    }

    public function test_every_export_is_audited_with_its_sections(): void
    {
        $this->csv(['sections' => ['summary', 'flags']]);

        $log = AuditLog::where('action', 'export')->where('details->report', 'Farm Production & Sales Report')->firstOrFail();
        $this->assertSame('csv', $log->details['format']);
        $this->assertSame('Summary, Flagged records (unresolved)', $log->details['sections']);
        $this->assertSame('2026-10-10 to 2026-10-13', $log->details['range']);
    }

    public function test_flagged_section_lists_only_unresolved_flags_in_range(): void
    {
        AuditLog::create(['action' => 'sold_gt_produced', 'model_type' => 'EggSale', 'model_id' => 1, 'details' => ['marker' => 'open-flag'], 'inconsistency_flagged' => true, 'inconsistency_rule' => 'sold_gt_produced']);
        AuditLog::create(['action' => 'sold_gt_produced', 'model_type' => 'EggSale', 'model_id' => 2, 'details' => ['marker' => 'closed-flag'], 'inconsistency_flagged' => true, 'inconsistency_rule' => 'sold_gt_produced', 'resolved' => true]);

        $body = $this->csv(['sections' => ['flags']]);
        $this->assertStringContainsString('open-flag', $body);
        $this->assertStringNotContainsString('closed-flag', $body);
    }

    public function test_staff_gets_403(): void
    {
        $staff = User::factory()->create(['role' => 'staff']);
        foreach (['pdf', 'csv', 'excel'] as $f) {
            $this->actingAs($staff)->get(route("reports.export.{$f}", $this->range))->assertForbidden();
        }
    }
}
