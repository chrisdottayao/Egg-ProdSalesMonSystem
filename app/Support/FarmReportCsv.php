<?php

namespace App\Support;

use Illuminate\Support\Carbon;
use Illuminate\Support\Str;

/**
 * Phase 3 item 11: the complete report as one CSV — a header block, then
 * each ticked section as a titled block separated by a blank row.
 */
class FarmReportCsv
{
    public static function rows(array $d): array
    {
        /** @var FarmReport $r */
        $r    = $d['report'];
        $rows = [
            [config('dashboard.farm_name') . ' — Farm Production & Sales Report'],
            ['Date range', $r->rangeText()],
            ['Filters', $r->filtersText()],
            ['Generated by', $d['generatedBy']->name . ' (' . $d['generatedBy']->role . ')'],
            ['Generated at (Asia/Manila)', $d['generatedAt']->format('Y-m-d H:i')],
            ['Sections included', $r->sectionsText()],
            ['Only approved records are included.'],
        ];

        foreach (FarmReport::SECTIONS as $key => $title) {
            if (! $r->includes($key)) {
                continue;
            }
            $rows[] = [];
            $rows[] = ['== ' . $title . ' =='];
            array_push($rows, ...self::section($key, $d));
        }

        $rows[] = [];
        $rows[] = ['== Basis & definitions =='];
        foreach ($d['definitions'] as $term => $text) {
            $rows[] = [$term, $text];
        }

        return $rows;
    }

    private static function money(float $v): string
    {
        return number_format($v, 2, '.', '');
    }

    private static function section(string $key, array $d): array
    {
        $s = $d['summary'];

        return match ($key) {
            'summary' => [
                ['Total eggs produced', $s['total_eggs_produced']],
                ['Total eggs sold', $s['total_eggs_sold']],
                ['Remaining eggs', $s['remaining_eggs']],
                ['Total mortality', $s['total_mortality']],
                ['Total revenue (PHP)', self::money($s['total_revenue'])],
                ['Total Feed & Electricity Expenses (PHP)', self::money($s['total_expenses'])],
                ['Net income (PHP)', self::money($s['net_income'])],
                ['Average production rate (%)', $s['avg_production_rate']],
                ['Average sales rate (%)', $s['avg_sales_rate']],
            ],
            'charts' => array_merge(
                [['Chart data: Egg Production Trend and Sales Revenue Trend'], ['Date', 'Eggs collected', 'Revenue (PHP)']],
                $d['dailyData']->map(fn ($x) => [$x['iso_date'], $x['eggs'], self::money($x['revenue'])])->all()
            ),
            'daily' => array_merge(
                [['Date', 'Eggs produced', 'Eggs sold', 'Mortality', 'Revenue (PHP)', 'Feed & Electricity Expenses (PHP)', 'Prod rate (%)', 'Remaining']],
                $d['dailyData']->map(fn ($x) => [$x['iso_date'], $x['eggs'], $x['sold'], $x['mortality'], self::money($x['revenue']), self::money($x['expenses']), $x['prod_rate'], $x['eggs'] - $x['sold'] - $x['spoiled']])->all(),
                [['TOTAL', $s['total_eggs_produced'], $s['total_eggs_sold'], $s['total_mortality'], self::money($s['total_revenue']), self::money($s['total_expenses']), $s['avg_production_rate'], $s['remaining_eggs']]]
            ),
            'buildings' => array_merge(
                [['Farm-wide prod rate (%)', $d['buildings']['farmProdRate']], ['Building', 'Population', 'Prod rate (%)', 'Status', 'Open alerts', 'As of']],
                collect($d['buildings']['leaderboard'])->map(fn ($x) => [
                    $x['building']->display_label, $x['population'], $x['prod_rate'], $x['band']['label'] ?? 'No data', $x['open_alerts_count'], $x['as_of']?->format('Y-m-d'),
                ])->all()
            ),
            'grading' => array_merge(
                [['Category', 'Pieces', 'Share (%)']],
                array_map(fn ($g) => [$g['category'], $g['pcs'], $g['share']], $d['grading']['rows']),
                [['TOTAL', $d['grading']['total'], $d['grading']['total'] > 0 ? 100 : '']]
            ),
            'sales' => array_merge(
                [array_merge(['Period', 'Eggs sold (pcs)', 'Trays', 'Cases', 'Revenue (PHP)', 'Avg price / pc (PHP)'], $d['salesData']['sizes'])],
                $d['salesData']['rows']->concat([$d['salesData']['totals']])->map(fn ($x) => array_merge(
                    [$x['label'], $x['pcs'], $x['trays'], $x['cases'], self::money($x['revenue']), $x['avg_price'] !== null ? self::money($x['avg_price']) : ''],
                    array_values($x['by_size'])
                ))->all()
            ),
            'expenses' => array_merge(
                [['Feed (PHP)', self::money($d['expenses']['feed'])], ['Electricity (PHP)', self::money($d['expenses']['electricity'])], ['Older categories (PHP)', self::money($d['expenses']['older'])], ['Total (PHP)', self::money($d['expenses']['total'])], ['Date', 'Category', 'Description', 'Building', 'Amount (PHP)', 'Estimated']],
                $d['expenses']['rows']->map(fn ($e) => [$e->date->format('Y-m-d'), $e->category_label, $e->description, $e->building?->display_label ?? 'Farm-wide', self::money($e->amount), $e->is_estimated ? 'Yes' : 'No'])->all()
            ),
            'culls' => array_merge(
                [['Total culled', $d['culls']['total_culled']], ['Total mortality', $d['culls']['total_mortality']], ['Date', 'Building', 'Culled', 'Reason', 'Heads sold', 'Buyer']],
                $d['culls']['rows']->map(fn ($c) => [$c->date->format('Y-m-d'), $c->henBatch?->display_label, $c->quantity_culled, $c->reason, $c->heads_sold, $c->buyer])->all()
            ),
            'alerts' => array_merge(
                [['Date', 'Type', 'Severity', 'Expected', 'Actual', 'Deviation (%)', 'Status', 'Description']],
                $d['alerts']->map(fn ($a) => [Carbon::parse($a->alert_date)->format('Y-m-d'), $a->type, $a->severity, $a->expected_value, $a->actual_value, $a->deviation_pct, $a->status, $a->description])->all()
            ),
            'forecast' => array_merge(
                ($d['forecast']['current']['active'] ?? false)
                    ? array_merge([['Model MAPE (%)', round((float) $d['forecast']['current']['mape'], 2)], ['Day', 'Forecast eggs']],
                        array_map(fn ($f) => [$f['day'], $f['predicted']], $d['forecast']['current']['forecast_7day']))
                    : [[$d['forecast']['current']['message'] ?? 'Forecast not active.']],
                [['Evaluated (Asia/Manila)', 'Records used', 'MAPE (%)', '7-day forecast total', '30-day forecast total']],
                $d['forecast']['evaluations']->map(fn ($e) => [$e->evaluated_at->copy()->setTimezone(ManilaDate::TZ)->format('Y-m-d H:i'), $e->trained_on, round((float) $e->mape, 2), $e->forecast_7day_total, $e->forecast_30day_total])->all(),
                [['AI insight (today)', $d['forecast']['ai_insight'] ?: 'None generated today.']]
            ),
            'batch' => array_merge(
                [['Batch', 'Collection date', 'Collected', 'Sold', 'Remaining', 'Spoilage', 'Sell-through (%)', 'Status']],
                $d['batches']->map(fn ($b) => ['HB-' . $b->id, $b->date->format('Y-m-d'), $b->eggs_collected, $b->quantity_sold, $b->remaining_stock, $b->spoilage_count ?? 0, $b->sell_through_rate, $b->batch_status])->all()
            ),
            'flags' => array_merge(
                [['When (Asia/Manila)', 'User', 'Rule', 'Record', 'Details']],
                $d['flags']->map(fn ($f) => [$f->created_at->copy()->setTimezone(ManilaDate::TZ)->format('Y-m-d H:i'), $f->user?->name, Str::headline($f->inconsistency_rule ?? ''), $f->module_label . ' #' . $f->model_id, AuditLogFilter::detailsText($f)])->all()
            ),
            default => [],
        };
    }
}
